SELECT
to_char(t1.JOURNAL_DATE_M, 'yyyymm') AS MONTH ,
t1.COMPANY_CODE , t1.COMPANY_NAME ,
t1.ACCOUNT_TYPE , t1.ACCOUNT_CODE ,t1.ACCOUNT_NAME ,
t1.DRCR_AMOUNT
FROM T_SETTL_M_COMP_9999A00 t1
WHERE t1.company_id = 3
AND t1.JOURNAL_DATE_M >= '2026-01-01'
AND t1.JOURNAL_DATE_M < '2026-02-01'
ORDER BY t1.JOURNAL_DATE_M , t1.COMPANY_CODE , t1.ACCOUNT_CODE
