SELECT
to_char(t1.JOURNAL_DATE_Y ,'yyyy') as "YEAR",
t1.COMPANY_CODE , t1.COMPANY_NAME ,
t1.ACCOUNT_TYPE , t1.ACCOUNT_CODE , t1.ACCOUNT_NAME ,
t1.DRCR_AMOUNT
FROM act1.T_SETTL_Y_COMP_9999A00 t1
WHERE t1.COMPANY_ID = 10
AND t1.JOURNAL_DATE_Y >= '2026-04-01'
AND t1.JOURNAL_DATE_Y < '2027-04-01'
ORDER BY 1, t1.COMPANY_CODE , t1.ACCOUNT_CODE
